import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../config.js';

/**
 * Image storage behind one small interface so the rest of the code does not care
 * where files live:
 *
 *   save(key, buffer, contentType)   store a file
 *   url(key)                         URL the browser can load it from
 *   remove(key)                      delete it (never throws)
 *
 * local  files on disk, served by Express from /uploads. Fine for development and
 *        for a single server with a mounted volume.
 * s3     a private bucket; the browser gets short-lived presigned URLs. On EC2 the
 *        credentials come from the instance role, so no keys live in the app.
 */

function localDriver() {
  const dir = config.storage.localDir;
  // Keys are generated by us, but resolve defensively so a key can never escape the folder.
  const resolve = (key) => {
    const full = path.resolve(dir, key);
    if (!full.startsWith(path.resolve(dir) + path.sep)) throw new Error('Invalid storage key');
    return full;
  };
  return {
    name: 'local',
    async save(key, buffer) {
      const full = resolve(key);
      await fs.mkdir(path.dirname(full), { recursive: true });
      await fs.writeFile(full, buffer);
    },
    async url(key) {
      return `/uploads/${key}`;
    },
    async remove(key) {
      if (!key) return;
      await fs.rm(resolve(key), { force: true }).catch(() => {});
    },
    async exists(key) {
      return fs.access(resolve(key)).then(() => true, () => false);
    },
    s3Uri() {
      return null; // only the S3 driver can hand files to other AWS services
    },
  };
}

async function s3Driver() {
  const { S3Client, PutObjectCommand, DeleteObjectCommand, GetObjectCommand, HeadObjectCommand } = await import('@aws-sdk/client-s3');
  const { getSignedUrl } = await import('@aws-sdk/s3-request-presigner');
  const { s3Bucket: Bucket, s3Region, s3Prefix, s3UrlTtlSeconds } = config.storage;
  if (!Bucket) throw new Error('STORAGE_DRIVER=s3 needs S3_BUCKET to be set');

  const client = new S3Client({
    region: s3Region,
    // Only set for S3-compatible stores such as MinIO in local testing.
    ...(process.env.S3_ENDPOINT ? { endpoint: process.env.S3_ENDPOINT, forcePathStyle: true } : {}),
  });
  const full = (key) => `${s3Prefix}${key}`;

  return {
    name: 's3',
    async save(key, buffer, contentType) {
      await client.send(
        new PutObjectCommand({ Bucket, Key: full(key), Body: buffer, ContentType: contentType, ServerSideEncryption: 'AES256' }),
      );
    },
    async url(key) {
      return getSignedUrl(client, new GetObjectCommand({ Bucket, Key: full(key) }), { expiresIn: s3UrlTtlSeconds });
    },
    async remove(key) {
      if (!key) return;
      await client.send(new DeleteObjectCommand({ Bucket, Key: full(key) })).catch(() => {});
    },
    async exists(key) {
      return client.send(new HeadObjectCommand({ Bucket, Key: full(key) })).then(() => true, () => false);
    },
    s3Uri(key) {
      return `s3://${Bucket}/${full(key)}`;
    },
  };
}

let driver = null;

async function get() {
  if (!driver) driver = config.storage.driver === 's3' ? await s3Driver() : localDriver();
  return driver;
}

export const storage = {
  async save(key, buffer, contentType) {
    return (await get()).save(key, buffer, contentType);
  },
  async url(key) {
    if (!key) return '';
    return (await get()).url(key);
  },
  async remove(key) {
    return (await get()).remove(key);
  },
  async exists(key) {
    return (await get()).exists(key);
  },
  /** `s3://bucket/key` for services such as Transcribe that read from S3; null on local disk. */
  async s3Uri(key) {
    return (await get()).s3Uri(key);
  },
  async driverName() {
    return (await get()).name;
  },
};
